/* ---------- storage ---------- */
var RATES_KEY = 'ps_rates';

interface RatesStore {
  values: Record<string, number>;
  verified: Record<string, string>;
}

function loadRates(): RatesStore {
  try {
    var raw = window.localStorage.getItem(RATES_KEY);
    if (raw) return JSON.parse(raw);
  } catch (e) { }
  return { values: {}, verified: {} };
}

function saveRates(store: RatesStore): void {
  try {
    window.localStorage.setItem(RATES_KEY, JSON.stringify(store));
  } catch (e) {
    PS.toast('Rates could not be saved to local storage.', 'danger');
  }
}

/* ---------- public API ---------- */

/** Get a rate's current value: the user's override, or the default. */
PS.rate = function (key: string): number {
  var def = PS.RATES.find(function (r) { return r.key === key; });
  if (!def) return NaN;
  var store = loadRates();
  return store.values[key] !== undefined ? store.values[key] : def.defaultValue;
};

/** Get a rate's full entry: definition, current value, verification state. */
PS.rateEntry = function (key: string): RateEntry | null {
  var def = PS.RATES.find(function (r) { return r.key === key; });
  if (!def) return null;
  var store = loadRates();
  var isDefault = store.values[key] === undefined;
  return Object.assign({}, def, {
    value: isDefault ? def.defaultValue : store.values[key],
    lastVerified: store.verified[key] || '',
    isDefault: isDefault
  });
};

/** Set a rate's value and optionally record when it was verified. */
PS.setRate = function (key: string, value: number, verifiedDate?: string): void {
  var store = loadRates();
  store.values[key] = value;
  if (verifiedDate) store.verified[key] = verifiedDate;
  saveRates(store);
};

/** Reset one rate to its default. */
PS.resetRate = function (key: string): void {
  var store = loadRates();
  delete store.values[key];
  delete store.verified[key];
  saveRates(store);
};

/** Reset every rate to its default. */
PS.resetRates = function (): void {
  saveRates({ values: {}, verified: {} });
};

/** All rate entries, for the Rates & Assumptions screen. */
PS.allRates = function (): RateEntry[] {
  return PS.RATES.map(function (r) { return PS.rateEntry(r.key)!; });
};

/** Prefill value for a calculator field that references a rate. */
PS.ratePrefill = function (key: string): string {
  var entry = PS.rateEntry(key);
  return entry ? String(entry.value) : '';
};
