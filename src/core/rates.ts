/* ==========================================================
   Procurement 360 — Rates & Assumptions Library
   ----------------------------------------------------------
   WHY THIS EXISTS

   A learning academy must never teach from a stale number.
   Tax rates change. Duty rates change. Cost of capital changes.
   If a calculator hardcodes 10% GST, it silently teaches the
   wrong answer the day the rate moves.

   THE RULE

   No rate is a constant inside a formula. Every rate is an input
   that prefills from this library. The user owns the library:
   they edit a rate once, every calculator uses their number,
   and each rate carries a basis note and a last-verified date
   the user sets themselves.

   THE HONESTY BANNER

   These are reference defaults, not authoritative rates. The
   tool says so on every screen that uses one.
   ========================================================== */
